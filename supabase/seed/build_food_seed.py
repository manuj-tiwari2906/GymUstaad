"""Build supabase/seed.sql from fitness_food_db_seed.xlsx.

Rules from the xlsx README and CLAUDE.md:
- Grade C rows and non-India rows are loaded but hidden (visible = false).
- Calculated xlsx columns are formulas without cached values, so they are not read.
- Diet tags are drafts; missing tags (fish, soy, jain) default to 'check', which the filter treats as blocked.

Usage: python build_food_seed.py  (needs openpyxl)
"""

from pathlib import Path

import openpyxl

HERE = Path(__file__).parent
XLSX = HERE / "fitness_food_db_seed.xlsx"
OUT = HERE.parent / "seed.sql"

REGION_BY_SETTING = {
    "Takeaway (UK/IE)": ("UK_IE", "takeaway"),
    "Restaurant (US)": ("US", "restaurant"),
    "Chain (US)": ("US", "chain"),
    "Home / unspecified": ("IN", "home"),
}
CONVERSION_STATUS = {"estimate, verify": "estimate", "needs rule": "needs_rule"}
DIET_TYPE = {"veg": "veg", "non-veg": "nonveg", "egg": "egg"}


def q(value):
    """SQL literal."""
    if value is None or value == "":
        return "null"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def rows(ws):
    header = [c.value for c in ws[1]]
    for row in ws.iter_rows(min_row=2, values_only=True):
        if any(v is not None for v in row):
            yield dict(zip(header, row))


def main():
    wb = openpyxl.load_workbook(XLSX, data_only=False)
    out = ["-- Generated by supabase/seed/build_food_seed.py. Do not edit by hand.", "begin;"]

    for r in rows(wb["Sources"]):
        out.append(
            "insert into public.food_sources (id, title, method, url) values "
            f"({q(r['source_id'])}, {q(r['what it is'])}, {q(r['how the numbers were obtained'])}, {q(r['link'])});"
        )

    for r in rows(wb["Dishes"]):
        region, place = REGION_BY_SETTING[r["setting"]]
        visible = region == "IN" and r["confidence"] in ("A", "B")
        per_100g = str(r["serving_desc"]).lower().startswith(("per 100 g", "100 g"))
        out.append(
            "insert into public.foods (legacy_id, name, category, log_mode, default_unit, food_state, region, visible) values "
            f"({q(r['id'])}, {q(r['dish'])}, {q(r['category'])}, 'dish', 'serving', {q(r['food_state'])}, "
            f"{q(region)}, {str(visible).lower()});"
        )
        food = f"(select id from public.foods where legacy_id = {q(r['id'])})"
        out.append(
            "insert into public.food_variants (food_id, place, serving_desc, serving_g, per_100g, kcal_low, kcal_typ, kcal_high, "
            "fat_g_low, fat_g_typ, fat_g_high, protein_g_typ, grade, source_id, notes) values "
            f"({food}, {q(place)}, {q(r['serving_desc'])}, {q(r['serving_g'])}, {str(per_100g).lower()}, "
            f"{q(r['kcal_low'])}, {q(r['kcal_typ'])}, {q(r['kcal_high'])}, {q(r['fat_g_low'])}, {q(r['fat_g_typ'])}, "
            f"{q(r['fat_g_high'])}, {q(r['protein_g_typ'])}, {q(r['confidence'])}, {q(r['source_id'])}, {q(r['notes'])});"
        )
        out.append(
            "insert into public.food_tags (food_id, contains_lactose, contains_gluten, contains_nuts, contains_egg, "
            "diet_type, light_digest, tag_status) values "
            f"({food}, {q(r['contains_lactose'])}, {q(r['contains_gluten'])}, {q(r['contains_nuts'])}, "
            f"{q(r['contains_egg'])}, {q(DIET_TYPE[r['diet_type']])}, {q(r['light_digest'])}, 'draft');"
        )

    for r in rows(wb["Conversions"]):
        low, high = r["cooked_g_per_100g_raw_low"], r["cooked_g_per_100g_raw_high"]
        out.append(
            "insert into public.food_conversions (label, from_state, to_state, factor_low, factor_high, status, notes) values "
            f"({q(r['food'])}, {q(r['raw_state'])}, {q(r['cooked_state'])}, "
            f"{q(float(low) / 100 if low else None)}, {q(float(high) / 100 if high else None)}, "
            f"{q(CONVERSION_STATUS[r['status']])}, {q(r['notes'])});"
        )

    for r in rows(wb["Backlog"]):
        out.append(
            "insert into public.food_backlog (priority, dish, category, setting, preferred_source, status, notes) values "
            f"({q(r['priority'])}, {q(r['dish'])}, {q(r['category'])}, {q(r['setting'])}, "
            f"{q(r['preferred_source'])}, {q(r['status'])}, {q(r['notes'])});"
        )

    out.append("commit;")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
